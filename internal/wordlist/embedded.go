package main

import (
	"fmt"
	"os"
	"strings"
)

func main() {
	// Read EFF wordlist
	effData, err := os.ReadFile("eff_large_wordlist.txt")
	if err != nil {
		panic(err)
	}
	effLines := strings.Split(strings.TrimSpace(string(effData)), "\n")
	var effWords []string
	for _, line := range effLines {
		parts := strings.SplitN(line, "\t", 2)
		if len(parts) >= 2 {
			effWords = append(effWords, strings.TrimSpace(parts[1]))
		}
	}

	// Read French wordlist
	frData, err := os.ReadFile("diceware-fr-5-jets.txt")
	if err != nil {
		panic(err)
	}
	frLines := strings.Split(strings.TrimSpace(string(frData)), "\n")
	var frWords []string
	for _, line := range frLines {
		parts := strings.SplitN(line, " ", 2)
		if len(parts) >= 2 {
			word := strings.TrimSpace(parts[1])
			// Only keep actual words
			if word != "" && !strings.ContainsAny(word, "=;:!@#$%^&*()_+[]{}|\\\"'<>,.?/0123456789") {
				frWords = append(frWords, word)
			}
		}
	}

	// Generate Go source
	fmt.Println("// Code generated by gen_embedded.go; DO NOT EDIT.")
	fmt.Println("")
	fmt.Println("package wordlist")
	fmt.Println("")
	fmt.Println("const (")
	fmt.Println("	effWordlistData = `")
	for _, w := range effWords {
		fmt.Println(w)
	}
	fmt.Println("`")
	fmt.Println("")
	fmt.Println("	frenchWordlistData = `")
	for _, w := range frWords {
		fmt.Println(w)
	}
	fmt.Println("`")
	fmt.Println(")")
}
